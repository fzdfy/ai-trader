const PLATFORM = { name: "Data Platform" };
const QUANT = { name: "Quant Research" };
const AGENT = { name: "Agent Platform" };
const OPERATOR = { name: "Super Administrator", role: "super_admin" };
const ALL_RESEARCH: ResearchConsumer[] = ["backtest", "screening", "stock_analysis"];

type AssetInput = {
  key: string;
  name: string;
  kind: GovernanceAsset["kind"];
  domain: DataDomain;
  tier: DataTier;
  description: string;
  grain: string;
  timeField: string;
  knownAtField?: string;
  primaryKey?: string[];
  consumers?: ResearchConsumer[];
  owner?: { name: string };
  steward?: { name: string };
  retention?: GovernanceAsset["retention"];
  classification?: GovernanceAsset["classification"];
  sourceStandards?: string[];
  upstream?: string[];
  downstream?: string[];
  jobs?: string[];
};

function asset(input: AssetInput): GovernanceAsset {
  const tierDefaultRetention: GovernanceAsset["retention"] =
    input.tier === "tier_0"
      ? { mode: "permanent", note: "关键数据长期保留并保持可追溯" }
      : input.kind === "application"
        ? { mode: "rebuildable", note: "随业务数据生命周期维护" }
        : { mode: "permanent", note: "按数据域保留策略维护" };
  return {
    key: input.key,
    name: input.name,
    kind: input.kind,
    domain: input.domain,
    tier: input.tier,
    responsibilities: {
      owner: input.owner ?? (input.domain === "application" ? AGENT : PLATFORM),
      steward: input.steward ?? QUANT,
      operator: OPERATOR,
    },
    classification: input.classification ?? "internal",
    retention: input.retention ?? tierDefaultRetention,
    contract: {
      businessDefinition: input.description,
      grain: input.grain,
      primaryKey: input.primaryKey ?? [],
      eventTimeField: input.timeField,
      ...(input.knownAtField ? { knownAtField: input.knownAtField } : {}),
      freshnessSlaHours: input.tier === "tier_0" ? 96 : 24 * 14,
      allowedConsumers: input.consumers ?? [],
    },
    sourceStandardRefs:
      input.sourceStandards ??
      (input.domain === "reference" ||
      input.domain === "market_raw" ||
      input.domain === "market_intelligence"
        ? ["a-stock-data"]
        : []),
    lineage: {
      upstreamAssets: input.upstream ?? [],
      downstreamAssets: input.downstream ?? [],
      jobTypes: input.jobs ?? [],
    },
  };
}

