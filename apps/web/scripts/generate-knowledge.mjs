// 构建期生成器：把 docs/*.md 内联为前端可 import 的 TS 模块。
// 唯一事实源是仓库根 docs/，本脚本只做「读取 + 结构化 + 序列化」，不加工内容。
// 用法：node scripts/generate-knowledge.mjs（由 package.json 的 dev/build 前置调用）
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(__dirname, "..");
const repoRoot = path.resolve(webDir, "..", "..");
const docsDir = path.join(repoRoot, "docs");
const outFile = path.join(webDir, "src", "generated", "knowledge.ts");

// 顺序 = 知识库左栏阅读顺序；label = 导航短名（title 取自文档首行 H1）。
const DOC_ORDER = [
  { file: "README.md", slug: "overview", label: "总览" },
  { file: "architecture.md", slug: "architecture", label: "架构" },
  { file: "data-pipeline.md", slug: "data-pipeline", label: "数据链路" },
  { file: "invariants.md", slug: "invariants", label: "铁律" },
  { file: "runbooks.md", slug: "runbooks", label: "排障手册" },
  { file: "decisions.md", slug: "decisions", label: "决策记录" },
  { file: "issues.md", slug: "issues", label: "已知缺陷" },
  { file: "glossary.md", slug: "glossary", label: "术语表" },
  { file: "roadmap.md", slug: "roadmap", label: "路线图" },
];

// 去掉标题里的 markdown 行内标记（反引号/链接/强调），用于生成纯文本 title。
function plainText(markdown) {
  return markdown
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[`*_~]/g, "")
    .trim();
}

// 抽出首行 H1 作为文档标题，并从正文中移除该行（阅读页会单独渲染标题）。
function splitTitle(markdown) {
  const match = markdown.match(/^\s*#\s+(.+?)\s*(?:\r?\n)+/);
  if (!match) return { title: "", body: markdown };
  return { title: plainText(match[1]), body: markdown.slice(match[0].length) };
}

async function main() {
  const docs = [];
  for (const { file, slug, label } of DOC_ORDER) {
    const raw = await readFile(path.join(docsDir, file), "utf8");
    const { title, body } = splitTitle(raw);
    docs.push({ slug, label, title: title || label, file, markdown: body });
  }

  const generatedAt = new Date().toISOString();
  const entries = docs
    .map(
      (doc) =>
        `  {\n` +
        `    slug: ${JSON.stringify(doc.slug)},\n` +
        `    label: ${JSON.stringify(doc.label)},\n` +
        `    title: ${JSON.stringify(doc.title)},\n` +
        `    file: ${JSON.stringify(doc.file)},\n` +
        `    markdown: ${JSON.stringify(doc.markdown)},\n` +
        `  },`,
    )
    .join("\n");

  const output =
    `// AUTO-GENERATED by apps/web/scripts/generate-knowledge.mjs — DO NOT EDIT.\n` +
    `// 事实源：仓库根 docs/*.md。修改文档后运行 \`pnpm --filter @ai-trader/web generate:knowledge\` 重新生成。\n\n` +
    `export interface KnowledgeDoc {\n` +
    `  slug: string;\n` +
    `  label: string;\n` +
    `  title: string;\n` +
    `  file: string;\n` +
    `  markdown: string;\n` +
    `}\n\n` +
    `export const KNOWLEDGE_GENERATED_AT = ${JSON.stringify(generatedAt)};\n\n` +
    `export const KNOWLEDGE_DOCS: KnowledgeDoc[] = [\n${entries}\n];\n`;

  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, output, "utf8");
  console.log(`[generate-knowledge] wrote ${docs.length} docs -> ${path.relative(repoRoot, outFile)}`);
}

main().catch((error) => {
  console.error("[generate-knowledge] failed:", error);
  process.exit(1);
});
